import React from 'react'
import { useParams, Link } from 'react-router-dom'
import { useStore } from '../../lib/store.jsx'
import { useCrm } from '../../lib/calc.js'
import { seesMoney } from '../../lib/perms.js'
import { Page, Button } from '../../components/ui.jsx'
import DocHeader from '../../components/DocHeader.jsx'
import { d, inr, words, today, fullName } from '../../lib/format.js'

// Payment summary (1 Nov): one A4 statement per booking with the Yamuna Sky City header.
// Consideration, demands raised, every counted receipt, TDS, outstanding, and the payment plan still to come.
export function PaymentSummary() {
  const { id } = useParams()
  const { user, settings } = useStore()
  const crm = useCrm()
  const c = crm.clients.find((x) => x.id === id || x.bookingId === id)
  if (!seesMoney(user)) return <Page title="Payment summary" back={true}><span className="locked">The payment summary with amounts is issued by finance</span></Page>
  if (!c) return <Page title="Booking not found" back={true} />
  const co = settings.company || {}
  const pays = c.payments.filter((p) => p.counted === 'Yes').sort((a, b) => String(a.date).localeCompare(String(b.date)))
  const plan = (settings.plans?.[c.funding === 'Bank loan' || /loan/i.test(c.funding || '') ? 'Bank loan' : 'Self'] || [])
  let run = 0
  return (
    <div>
      <div className="doc-tools no-print"><Link className="btn" to={'/crm/clients/' + c.id}>← Client 360</Link><Button variant="primary" onClick={() => window.print()}>Print or save as PDF</Button></div>
      <div className="doc">
        <DocHeader title="PAYMENT SUMMARY" sub={`As on ${d(today())}`} />
        <table><tbody>
          <tr><th style={{ width: '22%' }}>Allottee</th><td colSpan={3}><b>{fullName(c)}</b>{c.coapp ? ' & ' + c.coapp : ''}</td></tr>
          <tr><th>Residence</th><td>{c.unit} · {c.config} · floor {c.floor}</td><th style={{ width: '18%' }}>Saleable area</th><td>{c.area} sft</td></tr>
          <tr><th>Booking ID</th><td>{c.bookingId}</td><th>Client ID</th><td>{c.clientId}</td></tr>
          <tr><th>Booking date</th><td>{d(c.bookingDate)}</td><th>Funding</th><td>{c.funding || '–'}{c.loanBank ? ' · ' + c.loanBank : ''}</td></tr>
        </tbody></table>
        <div className="sec">Position</div>
        <table><tbody>
          <tr><td>Total consideration</td><td className="right">{inr(c.tc)}</td></tr>
          {Number(c.adjustment) > 0 && <tr><td>Less adjustment ({c.adjType || 'adjustment'})</td><td className="right">− {inr(c.adjustment)}</td></tr>}
          <tr><td>Demanded to date ({(crm.billedPct * 100).toFixed(1)}% of the plan, with GST {(crm.gst * 100).toFixed(0)}%)</td><td className="right">{inr(c.demand)}</td></tr>
          <tr><td>Received to date ({pays.length} receipts)</td><td className="right">{inr(c.received)}</td></tr>
          {c.tds > 0 && <tr><td>TDS deducted (Form 16B)</td><td className="right">{inr(c.tds)}</td></tr>}
          <tr className="total"><td>{c.outstanding > 0 ? 'Outstanding against demands raised' : 'Paid ahead of demands'}</td><td className="right">{inr(Math.abs(c.outstanding))}</td></tr>
        </tbody></table>
        {c.outstanding > 0 && <div className="words">Rupees {words(Math.round(c.outstanding))} only{c.due ? `, due ${d(c.due)}` : ''}</div>}
        <div className="sec">Receipts</div>
        <table><thead><tr><th>Date</th><th>Receipt</th><th>Towards</th><th>Mode</th><th>Ref.</th><th className="right">Amount</th><th className="right">Running total</th></tr></thead>
          <tbody>{pays.map((p) => { run += Number(p.amount || 0); return <tr key={p.id}><td className="nowrap">{d(p.date)}</td><td>{p.receiptNo}</td><td>{p.towards}</td><td>{p.mode}</td><td>{p.instrument || '–'}</td><td className="right">{inr(p.amount)}</td><td className="right">{inr(run)}</td></tr> })}
            {!pays.length && <tr><td colSpan={7} className="muted">No receipts yet</td></tr>}</tbody></table>
        <div className="sec">Payment plan · {c.funding || 'Self'}</div>
        <table><thead><tr><th>Stage</th><th className="right">%</th><th className="right">Amount (before GST)</th></tr></thead>
          <tbody>{plan.map((x) => <tr key={x.stage}><td>{x.stage}</td><td className="right">{(x.pct * 100).toFixed(1)}%</td><td className="right">{inr(Math.round(c.basis * x.pct))}</td></tr>)}</tbody></table>
        <div className="sec">Bank details for payments</div>
        <p style={{ margin: 0 }}>{co.name} · {co.bank} · A/c {co.account} · IFSC {co.ifsc} · {co.branch}</p>
        <div className="sign"><div>Prepared by {user.name}</div><div style={{ textAlign: 'right' }}>For {co.name}<br />Authorised signatory</div></div>
        <div className="foot">{co.address} · {co.contact} · Statement generated by Accord. Receipts are subject to realisation.</div>
      </div>
    </div>
  )
}
