const { record, field } = require('./vid.js')
module.exports = () => record('new-lead', async (v, page) => {
  await v.go('/crm/leads', 600)
  await v.card('Accord · Leads', 'Add a lead, or paste an enquiry', 'Every enquiry goes into Accord with a name, mobile and e-mail.')
  await v.say('Go to <b>Leads</b> and press <b>New lead</b>.')
  await v.click(page.getByRole('button', { name: 'New lead', exact: true }))
  await v.say('Name, mobile and e-mail are needed. Accord checks both.')
  await v.select(field(page, 'Title'), 'Mr.')
  await v.type(field(page, 'Name'), 'Sameer Kotian')
  await v.type(field(page, 'Mobile (primary)'), '9845012345')
  await v.type(field(page, 'Email'), 'sameer.kotian@example.com')
  await v.say('Pick the <b>Primary lead source</b>, and the advisor under <b>Assigned to</b>.')
  await v.select(field(page, 'Primary lead source'), 'Website')
  await v.select(field(page, 'Configuration interest'), '3 BHK')
  await v.select(field(page, 'Temperature'), 'Warm')
  await v.say('Press <b>Save lead</b>. The lead opens with its own ID.')
  await v.click(page.getByRole('button', { name: 'Save lead' }), { after: 1600 })
  await v.go('/crm/leads', 800)
  await v.say('An enquiry on WhatsApp or 99acres? Press <b>Paste an enquiry</b>.')
  await v.click(page.getByRole('button', { name: 'Paste an enquiry' }))
  await v.type(page.locator('.modal textarea').first(), 'Hi, I am Neeta Bhat, 98450 67890, neeta.bhat@example.com. Looking for a 4 BHK, will be in Mangaluru next week.', { delay: 12 })
  await v.say('Press <b>Read it into a new lead</b>.')
  await v.click(page.getByRole('button', { name: 'Read it into a new lead' }), { after: 900 })
  await v.say('Accord fills in the name, number, e-mail, city and BHK. Check them, then <b>Save lead</b>.', 1500)
  await v.point(page.getByRole('button', { name: 'Save lead' }), { ms: 1500 })
  await v.hideSay()
  await v.card('Find this again', 'Press <span style="color:#7A1C2E">?</span> and search', '<span class="q">“<b>add a new lead</b>” or “<b>paste enquiry</b>”</span>', 2600)
})
if (require.main === module) module.exports().catch((e) => { console.error(e); process.exit(1) })
